/*
 * Synopsis:
 *   char *GetTerraVisionBinaryName( void )
 *
 * Description:
 *   Looks up the Windows registry to see if we have a key to 
 *   tell us where the Netscape plugin was installed. This key
 *   is generated by the InstallShield installer. If no key is
 *   found, we hardwire to C:.
 *
 *   The user should NOT free the returned string.
 *
 * Returns: string containing the full pathname of the TV .exe
 *
 * Author: Martin Reddy
 *
 * Date: 7 August 2000
 *
 */

char *
GetTerraVisionBinaryName( void )
{
  char const *subkey = "Software\\SRI International\\TerraVision Plugin";
  HKEY        key;
  LONG        ret, key_type;
  static char install_dir[512] = "";
  long        length = 512;

  /* create a default install directory string hardwired to C: */

  strcpy(install_dir, "C:\\Program Files\\SRI International\\TerraVision Plugin");

  /* try to get the TerraVision Plugin registry key */

  ret = RegOpenKeyEx( HKEY_LOCAL_MACHINE, subkey, 0, KEY_EXECUTE, &key );
  if ( ret == ERROR_SUCCESS ) {

    /* extract the install directory string if present */

    RegQueryValueEx( key, "InstallDirectory", NULL, &key_type,
			   install_dir, &length );
    
    /* close the registry key that we just opened */

    RegCloseKey( key );
  }

  /* append the bin/TerraVision.exe part */

  strcat( install_dir, "\\bin\\TerraVision.exe" );

  return install_dir;
}

/*+++++++++++++++++++++++++++++++++++++++++++++++++
 * NPP_HandleEvent:
 * Mac-only, but stub must be present for Windows
 * Delivers a platform-specific event to the instance. 
 * 
 * On the Macintosh, event is a pointer to a standard Macintosh
 * EventRecord.  All standard event types are passed to the instance
 * as appropriate. In general, return TRUE if you handle the event and
 * FALSE if you ignore the event.
 * +++++++++++++++++++++++++++++++++++++++++++++++++*/

int16
NPP_HandleEvent( NPP instance, void *event )
{
  PluginInstance *plugin;
  int16 eventHandled = FALSE;
  
  if (instance == NULL)
    return eventHandled;
  
  plugin = (PluginInstance*) instance->pdata;
  eventHandled = PlatformHandleEvent( plugin, event );
  return eventHandled;
}

