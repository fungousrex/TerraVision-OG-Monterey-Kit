/*
 * Synopsis: TVStartLogging( TsLogFiles )
 *
 * Doc++ Description: *//**
 *   Turn on logging for the log file indicated by the 
 *   key passed in as a parameter. If it is already logging, nothing
 *   bad will/should happen.
 *
 * @param   logFile
 *
 * @return  TRUE - on success, FALSE - on failure
 *
 * @author  Stephen Lau
 * 
 * @version June 1995
 *
 * @see     TsLogFiles
 *
 */

int 
TsLogStartLogging( TsLogFiles logFile )
{
  static char *funcName = "TsLogStartLogging";

  if( tsLog == NULL ) {
    tsmError( funcName, "Hey idiot, try initializing the logger first" );
    return FALSE;
  }

  PR_Lock( tsLog->logLock ); {
    tsLog->logging[logFile] = TRUE;
  }; PR_Unlock( tsLog->logLock );

  return TRUE;
}

