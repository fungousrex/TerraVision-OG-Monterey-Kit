/*
 * Synopsis: static void TsLogUpdateBytesThisPeriod( double curr_secs )
 *
 * Description: This function will go through our list of timestamps
 *   for all tile read events and will remove all of those that are
 *   for events greater than "period" seconds ago. Because the list
 *   is time-ordered, we only need to recursively check the first 
 *   element of the list. When we remove a timestamp we also update
 *   the total number of bytes/tiles in this period accordingly.
 *
 * Returns: void
 *
 * Author: Martin Reddy
 * 
 * Date: 27 March 1999
 *
 */

static void
TsLogUpdateBytesThisPeriod( double curr_secs )
{
  int         inPeriod = FALSE;
  double      secs;
  ValLog      *event;
  list_iter_t iter;

  /* remove any events from the start of the list that are */
  /* beyond the time period for which we are monitoring.   */

  while ( inPeriod == FALSE && list_empty( timestamps ) == FALSE ) {

    /* look at the first event in the list */

    iter = list_first( timestamps );
    if ( ( event = (ValLog *) list_value( iter ) ) == NULL ) {
      list_unshift( timestamps );
      continue;
    }

    /* get it's timestamp and see how long ago it was */

    secs = DoubleSeconds( event->logTime );

    if ( secs < curr_secs - tsLog->period || secs > curr_secs ) {

      /* remove out of range timestamp event */

      list_unshift( timestamps );

      /* keep our running total up to date and free discarded event */

      tsLog->bytesThisPeriod -= event->val;
      tsLog->tilesThisPeriod--;

      tsmMemFree( event );

    } else

      /* we can stop now, all further events will be in range also */

      inPeriod = TRUE;
  }

}

/*
 * Synopsis: void TsLogBurstRate( int bytes )
 *
 * Description: This function takes the byte size of a tile that
 *   was just read and updates the network burst rate stats.
 *   We do this by maintaining a list of timestamps + byte size
 *   for each tile read. We have a running total of bytes within
 *   a certain "period" (default = 1 sec). When we add a new
 *   event or remove an old event from the list, we update this
 *   running total accordingly. This approach means that we don't
 *   have to total every timestamp's byte-size every time we
 *   want to know the total bytes in a period - this should make
 *   this implementation pretty efficient even when using a large
 *   period of interest.
 *
 * Returns: void
 *
 * Author: Martin Reddy
 * 
 * Date: 27 March 1999
 *
 */

void
TsLogBurstRate( int bytes )
{
  /* static const char funcName[] = "TsLogBurstRate"; */
  ValLog *event;

  /* do a quick sanity check */
  
  if ( bytes < 0 || timestamps == NULL ) return;

  /* create a new timestamp event for right now */
  
  if ( ( event = (ValLog *) tsmMemMalloc( sizeof(ValLog ) ) ) == NULL )
    return;

  PR_Lock( tsLog->logLock ); {

    /* fill the new timestamp event and add it to the end of our list */

    event->logTime = PR_IntervalNow();
    event->val = bytes;
    list_push( timestamps, event );

    /* update our running total for the new event */

    tsLog->bytesThisPeriod += bytes;     /* bytes in past "period" secs */
    tsLog->tilesThisPeriod++;

    tsLog->totalBytesRead += bytes;      /* bytes since start of app */
    tsLog->totalTilesRead++;

    /* now remove any events from the start of the list that are */
    /* beyond the time period for which we are monitoring. */

    TsLogUpdateBytesThisPeriod( DoubleSeconds( event->logTime ) );

  }; PR_Unlock( tsLog->logLock );

}

/*
 * Synopsis: double TsLogGetNetBurstRate( void )
 *
 * Description: This function returns the current network burst
 *   rate (Mbit/s). That is, how much data have we recently 
 *   streamed into the appliction from disk/network? This value
 *   is based upon the amount of bytes read over the most recent
 *   "period" seconds (default = 1 sec).
 *
 * Returns: The burst rate in units of Mbit/s
 *
 * Author: Martin Reddy
 * 
 * Date: 27 March 1999
 *
 */

double
TsLogGetNetBurstRate( void )
{
  /*static const char funcName[] = "TsLogGetNetBurstRate"; */
  double    result = 0.0;
  PRIntervalTime currTime;

  if ( tsLog == NULL || tsLog->bytesThisPeriod == 0 || tsLog->period <= 0.0 )
    return result;

  PR_Lock( tsLog->logLock ); {
    currTime = PR_IntervalNow();
    TsLogUpdateBytesThisPeriod( DoubleSeconds( currTime ) );
    result = 8 * 1e-6 * tsLog->bytesThisPeriod / tsLog->period;
  }; PR_Unlock( tsLog->logLock );

  return result;
}

