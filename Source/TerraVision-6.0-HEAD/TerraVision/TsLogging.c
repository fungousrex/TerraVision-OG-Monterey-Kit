/*
 * Synopsis: double DoubleSeconds()
 *
 * Doc++ Description: *//**
 *   Converts a PRIntervalTime structure to a number of seconds.
 *
 * @param currTime  input time, as a PRIntervalTime quantity.
 *  
 * @return   The seconds value as a double
 *
 * @author   Stephen Lau
 * 
 * @version  June 1995
 *
 */

double
DoubleSeconds( PRIntervalTime currTime )
{
  return (double)currTime / (double)PR_TicksPerSecond();
} 

/*
 * Synopsis: int TsLogRenderData()
 *
 * Description: Log how long it takes to render a frame
 *
 * Returns: TRUE = success, FALSE = failure
 *
 * Author: Stephen Lau
 * 
 * Date: June 1995
 *
 */

int
TsLogRenderData( PRIntervalTime startTime, PRIntervalTime endTime, double refresh,
		 int numDrawnPolys, int totalTextures, int newTextures )
{
  static char *funcName = "TsLogRenderData";
 
  PR_Lock( tsLog->logLock ); {
    tsLog->logHistory[TV_RENDER_LOG][tsLog->currLog[TV_RENDER_LOG]][0] = 
	startTime;
    tsLog->logHistory[TV_RENDER_LOG][tsLog->currLog[TV_RENDER_LOG]][1] =
	endTime;

    if ( tsLog->averages[TV_RENDER_LOG] == -1 )
      tsLog->averages[TV_RENDER_LOG] = tsmElapsedTime( startTime, endTime );
    else
      tsLog->averages[TV_RENDER_LOG] =
	tsLog->averages[TV_RENDER_LOG] * ( 1.0 - tsLog->weight ) +
	tsLog->weight *	tsmElapsedTime( startTime, endTime );

    if ( ++tsLog->currLog[TV_RENDER_LOG] == MAX_HISTORY_LOG )
      tsLog->currLog[TV_RENDER_LOG] = 0;

    if( totalTextures > 200 )
      tsmError( funcName, "Whoops textures %d > 200!", totalTextures );

    tsLog->numTextureLog[tsLog->currNumTexture][0].val = totalTextures;
    tsLog->numTextureLog[tsLog->currNumTexture][0].logTime = startTime;

    tsLog->numTextureLog[tsLog->currNumTexture][1].val = totalTextures;
    tsLog->numTextureLog[tsLog->currNumTexture][1].logTime = startTime;

    if ( ++tsLog->currNumTexture >= MAX_HISTORY_LOG )
      tsLog->currNumTexture = 0;

  }; PR_Unlock(tsLog->logLock);

  return TRUE;
}

