/*
 * Filename: ppm2c.c
 *
 * Purpose: takes a PPM image and writes out a piece of C code to stdout.
 *          The C code defines a string with the raw bits for the image.
 *          The pixels are output as 32-bit words, where the RGB ordering
 *          0BGR, i.e. the red_mask is 0x000000ff. This format is used by
 *          XCreateImage in the combinations that were tested.
 *
 * Revision: $Id: ppm2c.c,v 1.2 1999/04/16 00:06:59 leei Exp $
 *
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define TRUE 1
#define FALSE 0

int
main( int argc, char **argv )
{
  FILE *handle, *out;
  char buffer[512], name[512], *ptr;
  int  width, height, i, pixels, col;
  unsigned char r, g, b;
  int rgb_mode = FALSE;

  if ( argc < 3 ) {
    fprintf( stderr, "usage: ppm2c <in_filename> <out_filename> [-rgb]\n" );
    exit( 1 );
  } 

  if ( argc > 3 && strcmp( argv[3], "-rgb" ) == 0 ) rgb_mode = TRUE;

  /* open the ppm file */

  if ( ( handle = fopen( argv[1], "r" ) ) == NULL ) {
    fprintf( stderr, "cannot open file: %s\n", argv[1] );
    exit( 1 );
  }

  /* open the output file */

  if ( ( out = fopen( argv[2], "w" ) ) == NULL ) {
    fprintf( stderr, "cannot write to file: %s\n", argv[2] );
    fclose( handle );
    exit( 1 );
  }

  /* read the magic header of the PPM file and check that it is valid */

  fgets( buffer, 512, handle );
  if ( strcmp( buffer, "P6\n" ) ) {
    fprintf( stderr, "file is not a rawbits PPM: %s\n", argv[1] );
    fclose( handle );
    exit( 1 );
  }

  /* get the filename part without any extensions */

  if ( ( ptr = strrchr( argv[2], '/' ) ) == NULL )
    strcpy( name, argv[2] );
  else 
    strcpy( name, ptr );
  if ( ( ptr = strchr( name, '.' ) ) != NULL )
    *ptr = '\0';

  /* skip over any PPM comments */

  do {
    fgets( buffer, 512, handle );
  } while ( buffer[0] == '#' );

  /* read in the image dimnensions */

  sscanf( buffer, "%d %d", &width, &height );
  fgets( buffer, 512, handle );

  /* output the image dimensions in C code */

  fprintf( out, "/* automatically generated by ppm2c from %s */\n", argv[1] );
  fprintf( out, "static const int width_%s = %d;\n", name, width );
  fprintf( out, "static const int height_%s = %d;\n", name, height );
  fprintf( out, "static int depth_%s = %d;\n", name, ( rgb_mode ) ? 24 : 32 );
  fprintf( out, "static unsigned char bitmap_%s[] = {\n", name, height );

  /* output the pixels in a C string, using 0BGR pixel format */

  pixels = width * height;
  for ( i = col = 0; i < pixels; i++ ) {
    r = fgetc( handle );
    g = fgetc( handle );
    b = fgetc( handle );

    if ( feof( handle ) ) fprintf( stderr, "EOF! (pixel=%d)\n", i );

    if ( rgb_mode ) 
      sprintf( buffer, "%d,%d,%d", (int) r, (int) g, (int) b );
    else
      sprintf( buffer, "%d,%d,%d,%d", 0, (int) b, (int) g, (int) r );

    if ( i < pixels-1 ) strcat( buffer, "," );

    col += strlen( buffer );
    if ( col > 75 ) {
      fprintf( out, "\n%s", buffer ); 
      col = strlen(buffer);
    } else
      fprintf( out, buffer );

  }

  fprintf( out, "\n};\n" );
  fclose( out );
  fclose( handle );

  return 0;
}
